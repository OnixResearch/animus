#[derive(Deserialize)]
struct RawRegistry {
    schema: String,
    repository_id: String,
    registry_id: String,
    supported_cairn_schema: String,
    cairn_policy_hash: String,
    fallback_check_ids: Vec<String>,
    checks: Vec<RawCheck>,
}

#[derive(Deserialize)]
struct RawCheck {
    check_id: String,
    profile: String,
    argv: Vec<String>,
    affected_paths: Vec<String>,
    affected_crates: Vec<String>,
    affected_surfaces: Vec<String>,
    prerequisites: Vec<String>,
    capability: String,
    tier: String,
    risk: String,
    timeout_class: String,
    output_budget_class: String,
    expected_artifacts: Vec<String>,
    reproduction: RawReproduction,
    documentation_refs: Vec<String>,
    positive_contract: String,
    negative_contract: String,
}

#[derive(Deserialize)]
struct RawReproduction {
    argv: Vec<String>,
    working_root: String,
}

fn parse_capability(
    label: &str,
) -> Result<animus_runtime::authoritative_completion::CheckCapability, AgentCheckRegistryConfigError>
{
    match label {
        "cairn" => Ok(animus_runtime::authoritative_completion::CheckCapability::Cairn),
        "local-process" => {
            Ok(animus_runtime::authoritative_completion::CheckCapability::LocalProcess)
        }
        "nix" => Ok(animus_runtime::authoritative_completion::CheckCapability::Nix),
        unknown => Err(AgentCheckRegistryConfigError::UnsupportedCapability(
            unknown.to_string(),
        )),
    }
}

fn parse_tier(
    label: &str,
) -> Result<animus_runtime::authoritative_completion::CheckTier, AgentCheckRegistryConfigError> {
    match label {
        "quick" => Ok(animus_runtime::authoritative_completion::CheckTier::Quick),
        "standard" => Ok(animus_runtime::authoritative_completion::CheckTier::Standard),
        "full" => Ok(animus_runtime::authoritative_completion::CheckTier::Full),
        unknown => Err(AgentCheckRegistryConfigError::UnsupportedTier(
            unknown.to_string(),
        )),
    }
}

fn string_refs(values: &[String]) -> Vec<&str> {
    values.iter().map(String::as_str).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    const GENERATED_REGISTRY: &str =
        include_str!("../../../config/generated/agent-check-registry.json");

    #[test]
    fn generated_registry_revalidates_and_unknown_labels_fail_closed() {
        let registry = parse_agent_check_registry_json(GENERATED_REGISTRY)
            .expect("checked generated registry should revalidate");
        assert_eq!(registry.repository_id(), "onixresearch/animus");
        assert!(!registry.checks().is_empty());

        let unknown = GENERATED_REGISTRY.replacen(
            "\"capability\": \"nix\"",
            "\"capability\": \"ambient-shell\"",
            1,
        );
        assert!(matches!(
            parse_agent_check_registry_json(unknown.as_str()),
            Err(AgentCheckRegistryConfigError::UnsupportedCapability(_))
        ));
    }

    #[test]
    fn injected_service_traits_have_no_default_ambient_implementation() {
        struct Observer {
            calls: usize,
        }
        impl ChangedArtifactObservationService for Observer {
            type Error = ();

            fn observe(
                &mut self,
                _request: ChangedArtifactObservationRequest<'_>,
            ) -> Result<Vec<ObservedChangedArtifact>, Self::Error> {
                self.calls = self.calls.saturating_add(1);
                Ok(vec![ObservedChangedArtifact {
                    path: "crates/animus-runtime/src/lib.rs".to_string(),
                    surface: "rust".to_string(),
                    content_hash:
                        "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
                            .to_string(),
                }])
            }
        }

        let mut observer = Observer { calls: 0 };
        let observed = observer
            .observe(ChangedArtifactObservationRequest {
                workspace_label: "repository-root",
            })
            .expect("injected fixture should observe");
        assert_eq!(observer.calls, 1);
        assert_eq!(observed.len(), 1);
    }
}
