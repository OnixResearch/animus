//! Generated registry loader and injected authoritative-completion host ports.
//!
//! This standard-library shell may read checked generated JSON and invoke
//! caller-supplied services. It does not provide a default VCS implementation,
//! process runner, timer, artifact store, final-subject hasher, or Cairn client.
// r[impl agent_harness_runtime.authoritative_completion.boundary]

use std::path::Path;

use serde::Deserialize;

/// Generated registry parsing or loading failure.
#[derive(Debug)]
pub enum AgentCheckRegistryConfigError {
    /// Generated registry file could not be read.
    Read(std::io::Error),
    /// Generated bytes were not UTF-8.
    Utf8(std::str::Utf8Error),
    /// Generated JSON could not be decoded.
    Json(serde_json::Error),
    /// Capability label is unsupported.
    UnsupportedCapability(String),
    /// Tier label is unsupported.
    UnsupportedTier(String),
    /// Runtime registry revalidation failed.
    InvalidRegistry(Vec<animus_runtime::authoritative_completion::AgentCheckDiagnostic>),
}

impl core::fmt::Display for AgentCheckRegistryConfigError {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Read(error) => write!(formatter, "unable to read generated registry: {error}"),
            Self::Utf8(error) => write!(formatter, "generated registry is not UTF-8: {error}"),
            Self::Json(error) => write!(formatter, "unable to decode generated registry: {error}"),
            Self::UnsupportedCapability(label) => {
                write!(formatter, "unsupported generated capability: {label}")
            }
            Self::UnsupportedTier(label) => {
                write!(formatter, "unsupported generated tier: {label}")
            }
            Self::InvalidRegistry(issues) => write!(
                formatter,
                "generated registry failed runtime revalidation with {} issue(s)",
                issues.len()
            ),
        }
    }
}

impl std::error::Error for AgentCheckRegistryConfigError {}

/// Loads checked generated registry JSON from an explicit host path.
///
/// # Errors
///
/// Returns [`AgentCheckRegistryConfigError`] for read, decode, label, or runtime
/// revalidation failures.
pub fn load_agent_check_registry(
    path: &Path,
) -> Result<
    animus_runtime::authoritative_completion::AgentCheckRegistry,
    AgentCheckRegistryConfigError,
> {
    let bytes = std::fs::read(path).map_err(AgentCheckRegistryConfigError::Read)?;
    let text =
        std::str::from_utf8(bytes.as_slice()).map_err(AgentCheckRegistryConfigError::Utf8)?;
    parse_agent_check_registry_json(text)
}

/// Parses checked generated registry JSON and revalidates it in runtime logic.
///
/// # Errors
///
/// Returns [`AgentCheckRegistryConfigError`] for malformed JSON, unsupported
/// enum labels, or a registry contract violation.
pub fn parse_agent_check_registry_json(
    input: &str,
) -> Result<
    animus_runtime::authoritative_completion::AgentCheckRegistry,
    AgentCheckRegistryConfigError,
> {
    let raw: RawRegistry =
        serde_json::from_str(input).map_err(AgentCheckRegistryConfigError::Json)?;
    let capabilities = raw
        .checks
        .iter()
        .map(|row| parse_capability(row.capability.as_str()))
        .collect::<Result<Vec<_>, _>>()?;
    let tiers = raw
        .checks
        .iter()
        .map(|row| parse_tier(row.tier.as_str()))
        .collect::<Result<Vec<_>, _>>()?;
    let argv_refs = raw
        .checks
        .iter()
        .map(|row| string_refs(row.argv.as_slice()))
        .collect::<Vec<_>>();
    let path_refs = raw
        .checks
        .iter()
        .map(|row| string_refs(row.affected_paths.as_slice()))
        .collect::<Vec<_>>();
    let crate_refs = raw
        .checks
        .iter()
        .map(|row| string_refs(row.affected_crates.as_slice()))
        .collect::<Vec<_>>();
    let surface_refs = raw
        .checks
        .iter()
        .map(|row| string_refs(row.affected_surfaces.as_slice()))
        .collect::<Vec<_>>();
    let prerequisite_refs = raw
        .checks
        .iter()
        .map(|row| string_refs(row.prerequisites.as_slice()))
        .collect::<Vec<_>>();
    let artifact_refs = raw
        .checks
        .iter()
        .map(|row| string_refs(row.expected_artifacts.as_slice()))
        .collect::<Vec<_>>();
    let reproduction_refs = raw
        .checks
        .iter()
        .map(|row| string_refs(row.reproduction.argv.as_slice()))
        .collect::<Vec<_>>();
    let documentation_refs = raw
        .checks
        .iter()
        .map(|row| string_refs(row.documentation_refs.as_slice()))
        .collect::<Vec<_>>();
    let rows = raw
        .checks
        .iter()
        .enumerate()
        .map(
            |(index, row)| animus_runtime::authoritative_completion::AgentCheckRowDraft {
                check_id: row.check_id.as_str(),
                profile: row.profile.as_str(),
                argv: argv_refs[index].as_slice(),
                affected_paths: path_refs[index].as_slice(),
                affected_crates: crate_refs[index].as_slice(),
                affected_surfaces: surface_refs[index].as_slice(),
                prerequisites: prerequisite_refs[index].as_slice(),
                capability: capabilities[index],
                tier: tiers[index],
                risk: row.risk.as_str(),
                timeout_class: row.timeout_class.as_str(),
                output_budget_class: row.output_budget_class.as_str(),
                expected_artifacts: artifact_refs[index].as_slice(),
                reproduction_argv: reproduction_refs[index].as_slice(),
                working_root: row.reproduction.working_root.as_str(),
                documentation_refs: documentation_refs[index].as_slice(),
                positive_contract: row.positive_contract.as_str(),
                negative_contract: row.negative_contract.as_str(),
            },
        )
        .collect::<Vec<_>>();
    let fallback = string_refs(raw.fallback_check_ids.as_slice());
    let draft = animus_runtime::authoritative_completion::AgentCheckRegistryDraft {
        schema: raw.schema.as_str(),
        repository_id: raw.repository_id.as_str(),
        registry_id: raw.registry_id.as_str(),
        supported_cairn_schema: raw.supported_cairn_schema.as_str(),
        cairn_policy_hash: raw.cairn_policy_hash.as_str(),
        fallback_check_ids: fallback.as_slice(),
        checks: rows.as_slice(),
    };
    animus_runtime::authoritative_completion::validate_agent_check_registry(&draft)
        .map_err(AgentCheckRegistryConfigError::InvalidRegistry)
}

/// Host-owned changed-artifact observation request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ChangedArtifactObservationRequest<'a> {
    /// Safe workspace label selected by host policy.
    pub workspace_label: &'a str,
}

/// Host-owned changed-artifact observation.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ObservedChangedArtifact {
    /// Repository-relative changed path.
    pub path: String,
    /// Safe affected surface label.
    pub surface: String,
    /// BLAKE3 content identity.
    pub content_hash: String,
}

/// Injected VCS or explicit-path observation service.
pub trait ChangedArtifactObservationService {
    /// Host-private observation failure.
    type Error;

    /// Observes a bounded final change snapshot.
    ///
    /// # Errors
    ///
    /// Returns the host-private error without retrying or escalating.
    fn observe(
        &mut self,
        request: ChangedArtifactObservationRequest<'_>,
    ) -> Result<Vec<ObservedChangedArtifact>, Self::Error>;
}

/// Host-owned final-subject hashing request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct FinalSubjectHashRequest<'a> {
    /// BLAKE3 identity of the changed-artifact snapshot.
    pub changed_artifact_hash: &'a str,
    /// Registry identity used for selection.
    pub registry_hash: &'a str,
    /// Policy identity used for selection.
    pub policy_hash: &'a str,
}

/// Injected final-subject identity service.
pub trait FinalSubjectHashService {
    /// Host-private hashing failure.
    type Error;

    /// Produces the final subject BLAKE3 identity.
    ///
    /// # Errors
    ///
    /// Returns the host-private error without guessing an identity.
    fn final_subject_hash(
        &mut self,
        request: FinalSubjectHashRequest<'_>,
    ) -> Result<String, Self::Error>;
}

/// Host-owned bounded check execution request.
#[derive(Clone, Copy, Debug)]
pub struct AgentCheckExecutionRequest<'a> {
    /// Selected required check.
    pub check: &'a animus_runtime::authoritative_completion::CairnRequiredCheck,
    /// Registry identity.
    pub registry_hash: &'a str,
    /// Selection identity.
    pub selection_hash: &'a str,
    /// Cairn policy identity.
    pub policy_hash: &'a str,
    /// Final subject identity.
    pub final_subject_hash: &'a str,
}

/// Host-produced safe artifact observation.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HostArtifactObservation {
    /// Repository-relative artifact path.
    pub path: String,
    /// BLAKE3 artifact identity.
    pub hash: String,
}

/// Host-produced bounded execution observation.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HostCheckExecutionObservation {
    /// Exact result status.
    pub status: animus_runtime::authoritative_completion::CheckStatus,
    /// BLAKE3 identity of bounded evidence.
    pub evidence_hash: String,
    /// BLAKE3 identity of the execution receipt.
    pub execution_receipt_hash: String,
    /// Optional process exit code.
    pub exit_code: Option<i32>,
    /// Optional terminating signal.
    pub signal: Option<i32>,
    /// Whether execution timed out.
    pub timed_out: bool,
    /// Whether process-group cleanup completed.
    pub cleanup_complete: bool,
    /// Bounded stdout byte count.
    pub stdout_bytes: u64,
    /// Bounded stderr byte count.
    pub stderr_bytes: u64,
    /// BLAKE3 stdout identity.
    pub stdout_hash: String,
    /// BLAKE3 stderr identity.
    pub stderr_hash: String,
    /// Safe artifact observations.
    pub artifacts: Vec<HostArtifactObservation>,
}

/// Injected bounded check execution service.
pub trait AgentCheckExecutionService {
    /// Host-private execution failure.
    type Error;

    /// Executes one admitted exact check request.
    ///
    /// # Errors
    ///
    /// Returns the host-private error without rewriting it as a passing check.
    fn execute(
        &mut self,
        request: AgentCheckExecutionRequest<'_>,
    ) -> Result<HostCheckExecutionObservation, Self::Error>;
}

